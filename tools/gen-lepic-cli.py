"""Generates the lepic command reference from the binary's own --help.

    tools/gen-lepic-cli.py --bin <path to the lepic binary>

Build the binary from LEPIC main (`cargo build --release -p lepic-cli`) and pass it with --bin
(or set LEPIC_BIN). The script walks every command through `lepic <command> --help` and writes
site/docs/developers/lepic/cli/reference.md. The output is generated: change LEPIC's help text or
this script, not the page. The task-first page next to it, cli/index.md, is written by hand.

The script runs the binary with an empty HOME and no LEPIC_* variables, so the help shows the
defaults and nothing of the machine it ran on.
"""
import argparse
import os
import re
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / 'site/docs/developers/lepic/cli/reference.md'


def run_help(binary, path, home):
    env = {k: v for k, v in os.environ.items() if not k.startswith('LEPIC_')}
    env.update(HOME=home, USERPROFILE=home, NO_COLOR='1', COLUMNS='100')
    out = subprocess.run([binary, *path, '--help'], capture_output=True, text=True, env=env,
                         timeout=30, check=True)
    return out.stdout.rstrip('\n')


def subcommands(text):
    """Names under the `Commands:` heading, without clap's own `help`."""
    names, inside = [], False
    for line in text.splitlines():
        if line == 'Commands:':
            inside = True
        elif inside:
            m = re.match(r'  (\S+)\s{2,}\S|  (\S+)$', line)
            if m:
                names.append(m.group(1) or m.group(2))
            elif line.strip() == '' or not line.startswith(' '):
                if line.strip() == '' or not line.startswith(' '):
                    break
    return [n for n in names if n != 'help']


def split_global(text):
    """(help without its `Global options:` block, that block)."""
    lines = text.splitlines()
    for i, line in enumerate(lines):
        if line == 'Global options:':
            j = i + 1
            while j < len(lines) and (lines[j].startswith(' ') or lines[j] == ''):
                # a blank line followed by an unindented line ends the block
                if lines[j] == '' and (j + 1 >= len(lines) or not lines[j + 1].startswith(' ')):
                    break
                j += 1
            return '\n'.join(lines[:i] + lines[j + 1:]).rstrip('\n'), '\n'.join(lines[i:j])
    return text, ''


def walk(binary, home, path, depth, sections, top=None):
    text = run_help(binary, path, home)
    body, glob = split_global(text)
    if top is not None and top['global'] is None:
        top['global'] = glob
    name = ' '.join(['lepic', *path])
    sections.append((depth, name, body))
    for sub in subcommands(text):
        walk(binary, home, [*path, sub], depth + 1, sections, top)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--bin', default=os.environ.get('LEPIC_BIN'))
    args = ap.parse_args()
    if not args.bin:
        sys.exit('gen-lepic-cli: pass --bin <lepic binary> or set LEPIC_BIN')
    binary = str(Path(args.bin).resolve())
    version = subprocess.run([binary, '--version'], capture_output=True, text=True, check=True).stdout.strip()
    with tempfile.TemporaryDirectory() as home:
        sections, top = [], {'global': None}
        walk(binary, home, [], 0, sections, top)

    root_body = sections[0][2]
    # The top help ends with the exit codes: they get their own section.
    root_body, _, exit_codes = root_body.partition('\nExit codes:\n')
    lines = [
        '---', 'title: lepic command reference',
        'toc_max_heading_level: 4',
        'description: "Every lepic command and option, generated from the binary\'s own help."',
        '---', '',
        '<!-- Generated by tools/gen-lepic-cli.py from `lepic --help`. Do not edit. -->', '',
        '# lepic command reference', '',
        f'Generated from the help of `{version}`. The same text is in `lepic <command> --help`. '
        'Task-first examples are on the [command-line wallet](index.md) page.', '',
        '## Global options', '',
        'Every command takes these options, before or after the command name. A flag overrides its '
        'environment variable, which overrides the config file.', '',
        '```text', top['global'].replace('Global options:\n', '', 1), '```', '',
        '## Exit codes', '', '```text', exit_codes.rstrip(), '```', '',
        '## The lepic command', '', '```text', root_body, '```', '']
    for depth, name, body in sections[1:]:
        lines += ['#' * min(depth + 1, 4) + f' {name}', '', '```text', body, '```', '']
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text('\n'.join(lines).rstrip() + '\n')
    print(f'wrote {OUT.relative_to(ROOT)}: {len(sections)} commands, {version}')


if __name__ == '__main__':
    main()
